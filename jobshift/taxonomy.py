# 子類 → 大類的扁平對照
INDUSTRY_TO_CLASS: dict[str, str] = {
    sub: major for major, subs in INDUSTRY_CLASSIFICATION.items() for sub in subs
}


def classify_industry(industry_name: str | None) -> str:
    """公司行業名 → A–S 大類。對不到就是「未分類」，不猜。"""
    if not industry_name:
        return UNKNOWN_CLASS
    return INDUSTRY_TO_CLASS.get(industry_name.strip(), UNKNOWN_CLASS)


def bucket_label(bucket: str | None) -> str:
    """職務類別桶 → 中文名。給人看的一律走這裡，不要直接顯示原始 key。"""
    if not bucket:
        return UNKNOWN_CLASS
    return BUCKET_LABELS.get(bucket, bucket)
